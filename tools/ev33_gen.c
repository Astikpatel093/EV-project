/* ev33_gen - deterministic scenario generator.
 *
 *   ev33_gen --profile small|medium|large|adversarial|shock [--seed N] --out DIR
 *
 * Profiles
 *   small        6x6 grid city, 12 candidate sites, 60 trips (hand-checkable)
 *   medium      16x16 grid city, 60 sites, 1200 trips  (normal operation)
 *   shock       medium + budget cut, port outages, river-bridge closure, 60% demand surge
 *   large       32x32 grid city, 220 sites, 6000 trips (stress)
 *   adversarial 2x200 corridor, equal costs, identical departure times, fault-burst log
 */
#include "ev_mem.h"

#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#ifdef _WIN32
#include <direct.h>
#define MKDIR(p) _mkdir(p)
#else
#define MKDIR(p) mkdir(p, 0755)
#endif

typedef struct {
    const char *name;
    int rows, cols;
    double spacing;
    double diag_p;
    int sites, trips;
    int budget;
    double soc_lo, soc_hi;
    double grid_kw;
    long events;
    int corridor;   /* adversarial layout */
    int shock;
} profile;

static const profile PROFILES[] = {
    { "small", 6, 6, 6.0, 0.30, 12, 60, 200, 0.15, 0.45, 120, 2000, 0, 0 },
    { "medium", 16, 16, 4.5, 0.25, 60, 1200, 900, 0.20, 0.75, 900, 50000, 0, 0 },
    { "shock", 16, 16, 4.5, 0.25, 60, 1200, 900, 0.20, 0.75, 900, 50000, 0, 1 },
    { "large", 32, 32, 3.5, 0.25, 220, 6000, 2500, 0.20, 0.75, 4000, 400000, 0, 0 },
    { "adversarial", 2, 200, 3.0, 0.00, 80, 1500, 600, 0.20, 0.35, 900, 200000, 1, 0 },
};

static double gauss(ev_rng *r) {
    double u = ev_rng_unit(r) + 1e-12, v = ev_rng_unit(r);
    return sqrt(-2 * log(u)) * cos(6.283185307179586 * v);
}

static void usage(void) {
    fprintf(stderr, "usage: ev33_gen --profile small|medium|shock|large|adversarial [--seed N] --out DIR\n");
}

int main(int argc, char **argv) {
    const char *pname = NULL, *out = NULL;
    unsigned long long seed = 33;
    for (int i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "--profile") && i + 1 < argc) pname = argv[++i];
        else if (!strcmp(argv[i], "--seed") && i + 1 < argc) seed = strtoull(argv[++i], NULL, 10);
        else if (!strcmp(argv[i], "--out") && i + 1 < argc) out = argv[++i];
        else { usage(); return 1; }
    }
    if (!pname || !out) { usage(); return 1; }
    const profile *P = NULL;
    for (size_t k = 0; k < sizeof PROFILES / sizeof PROFILES[0]; k++) if (!strcmp(PROFILES[k].name, pname)) P = &PROFILES[k];
    if (!P) { fprintf(stderr, "unknown profile '%s'\n", pname); usage(); return 1; }
    MKDIR(out);

    ev_rng rng;
    ev_rng_seed(&rng, seed);
    int R = P->rows, C = P->cols, N = R * C;
    double *x = malloc(sizeof(double) * N), *y = malloc(sizeof(double) * N), *z = malloc(sizeof(double) * N);
    int *dem = malloc(sizeof(int) * N), *id = malloc(sizeof(int) * N);
    double cx = (C - 1) * P->spacing / 2, cy = (R - 1) * P->spacing / 2;
    for (int r = 0; r < R; r++)
        for (int c = 0; c < C; c++) {
            int i = r * C + c;
            id[i] = 1000 + 7 * i;              /* non-contiguous ids exercise the binary-search index */
            x[i] = c * P->spacing + (ev_rng_unit(&rng) - 0.5) * P->spacing * 0.3;
            y[i] = r * P->spacing + (ev_rng_unit(&rng) - 0.5) * P->spacing * 0.3;
            /* rolling terrain plus (outside the corridor) a steep escarpment ~2/3 across the map,
             * like the climb from a valley city to a hill town: downhill arcs there have negative
             * energy (regeneration), which is why Bellman-Ford is offered as a routing strategy */
            double xr = (C - 1) * P->spacing * 0.68;
            z[i] = 450 + 260 * sin(x[i] / 11.0) * cos(y[i] / 13.0);
            if (P->corridor) z[i] = 300 + 0.8 * x[i] + 40 * sin(x[i] / 7.0);
            else {
                /* one low pass through the ridge: the energy-optimal route detours through it */
                double yp = (R - 1) * P->spacing * 0.2, gap = exp(-((y[i] - yp) * (y[i] - yp)) / 30.0);
                z[i] += 900.0 * (1.0 - 0.85 * gap) / (1.0 + exp(-(x[i] - xr) / 2.5));
            }
            double d2 = ((x[i] - cx) * (x[i] - cx) + (y[i] - cy) * (y[i] - cy)) / (cx * cx + cy * cy + 1);
            dem[i] = (int)(60 * exp(-3 * d2)) + (int)ev_rng_range(&rng, 0, 10);
            if (P->corridor && (c < 10 || c > C - 11)) dem[i] += 80; /* two terminal cities */
        }

    char path[1024];
    snprintf(path, sizeof path, "%s/nodes.csv", out);
    FILE *f = fopen(path, "w");
    if (!f) { perror(path); return 1; }
    fprintf(f, "# generated by ev33_gen profile=%s seed=%llu\nid,name,x_km,y_km,elev_m,demand\n", P->name, seed);
    for (int i = 0; i < N; i++) fprintf(f, "%d,J%02d-%02d,%.3f,%.3f,%.1f,%d\n", id[i], i / C, i % C, x[i], y[i], z[i], dem[i]);
    fclose(f);

    /* roads */
    snprintf(path, sizeof path, "%s/edges.csv", out);
    f = fopen(path, "w");
    fprintf(f, "u,v,km,capacity\n");
    int river = C / 2; /* shock: the bridges across the middle column close except two */
    int edges = 0;
    for (int r = 0; r < R; r++)
        for (int c = 0; c < C; c++) {
            int i = r * C + c;
            int nb[3] = { -1, -1, -1 };
            if (c + 1 < C) nb[0] = i + 1;
            if (r + 1 < R) nb[1] = i + C;
            if (c + 1 < C && r + 1 < R && ev_rng_unit(&rng) < P->diag_p) nb[2] = i + C + 1;
            for (int k = 0; k < 3; k++) {
                int j = nb[k];
                if (j < 0) continue;
                int crosses = (c == river - 1) && (k == 0 || k == 2);
                if (P->shock && crosses && r != R / 4 && r != 3 * R / 4) continue;
                double d = sqrt((x[i] - x[j]) * (x[i] - x[j]) + (y[i] - y[j]) * (y[i] - y[j]));
                double km = d * (1.05 + 0.2 * ev_rng_unit(&rng));
                fprintf(f, "%d,%d,%.3f,%ld\n", id[i], id[j], km, ev_rng_range(&rng, 40, 200));
                edges++;
            }
        }
    fclose(f);

    /* candidate sites */
    snprintf(path, sizeof path, "%s/stations.csv", out);
    f = fopen(path, "w");
    fprintf(f, "id,node,cost,ports,power_kw,maint_period_h,maint_offset_h\n");
    unsigned char *used = calloc((size_t)N, 1);
    static const int periods[] = { 24, 36, 48, 60, 72, 96, 168 };
    static const double powers[] = { 30, 60, 120 };
    for (int s = 0; s < P->sites; s++) {
        int i;
        if (P->corridor) i = (s * C / P->sites) + (s % 2) * C;     /* evenly along the corridor */
        else do { i = (int)ev_rng_range(&rng, 0, N - 1); } while (used[i]);
        used[i] = 1;
        int cost = P->corridor ? 25 : (int)(25 + ev_rng_range(&rng, 0, 60) + dem[i]); /* land is dearer downtown */
        int ports = (int)ev_rng_range(&rng, 2, 8);
        if (P->shock && ev_rng_unit(&rng) < 0.30) ports = 1;          /* port outages */
        double pw = powers[ev_rng_range(&rng, 0, 2)];
        int per = periods[ev_rng_range(&rng, 0, 6)];
        fprintf(f, "%d,%d,%d,%d,%.0f,%d,%ld\n", 500 + s, id[i], cost, ports, pw, per, ev_rng_range(&rng, 0, per - 1));
    }
    fclose(f);

    /* trips: demand-weighted endpoints, bimodal commuter departures */
    long dsum = 0;
    for (int i = 0; i < N; i++) dsum += dem[i] + 1;
    int ntrips = P->shock ? (int)(P->trips * 1.6) : P->trips;
    snprintf(path, sizeof path, "%s/trips.csv", out);
    f = fopen(path, "w");
    fprintf(f, "id,src,dst,depart_min,soc0\n");
    for (int t = 0; t < ntrips; t++) {
        int a, b;
        for (;;) {
            long pick = ev_rng_range(&rng, 0, dsum - 1);
            a = 0; while (pick >= dem[a] + 1) { pick -= dem[a] + 1; a++; }
            if (P->corridor) {
                a = (t % 2) ? (int)ev_rng_range(&rng, 0, 9) : C - 1 - (int)ev_rng_range(&rng, 0, 9);
                b = (t % 2) ? C - 1 - (int)ev_rng_range(&rng, 0, 9) : (int)ev_rng_range(&rng, 0, 9);
                a += (int)ev_rng_range(&rng, 0, 1) * C; b += (int)ev_rng_range(&rng, 0, 1) * C;
            } else b = (int)ev_rng_range(&rng, 0, N - 1);
            if (a != b) break;
        }
        int dep;
        if (P->corridor) dep = 6 * 60;                                   /* identical keys */
        else {
            double u = ev_rng_unit(&rng);
            double h = u < 0.4 ? 8.5 + gauss(&rng) : u < 0.8 ? 18.0 + 1.2 * gauss(&rng) : 24 * ev_rng_unit(&rng);
            if (P->shock && t >= P->trips) h = 17.5 + 0.7 * gauss(&rng);  /* surge in the evening peak */
            if (h < 0) h = 0;
            if (h > 23.9) h = 23.9;
            dep = (int)(h * 60);
        }
        double soc = P->soc_lo + (P->soc_hi - P->soc_lo) * ev_rng_unit(&rng);
        fprintf(f, "%d,%d,%d,%d,%.3f\n", 1 + t, id[a], id[b], dep, soc);
    }
    fclose(f);

    /* scenario config */
    snprintf(path, sizeof path, "%s/scenario.cfg", out);
    f = fopen(path, "w");
    fprintf(f, "# EV33 scenario (%s)\nname = %s\n", P->name, P->name);
    fprintf(f, "budget = %d\n", P->shock ? (int)(P->budget * 0.55) : P->budget);
    fprintf(f, "battery_kwh = 30\nconsumption_kwh_per_km = 0.18\nreserve_frac = 0.10\ntarget_frac = 0.80\n");
    fprintf(f, "regen_eff = 0.60\nelev_kwh_per_m = 0.0045\nspeed_kmh = 40\nmax_detour_km = 15\n");
    fprintf(f, "grid_kw = %.0f\nwindow_min = 120\nsession_min = 30\nhorizon_h = 24\n", P->shock ? P->grid_kw * 0.6 : P->grid_kw);
    fclose(f);

    /* station event log: C=charge start E=end I=idle F=fault O=offline R=reset */
    snprintf(path, sizeof path, "%s/events.txt", out);
    f = fopen(path, "w");
    char st = 'I';
    double pf = P->shock ? 0.06 : 0.02;
    for (long k = 0; k < P->events; k++) {
        if (P->corridor) st = (k % 997 == 996) ? 'R' : 'F';              /* near-worst case for naive matching */
        else {
            double u = ev_rng_unit(&rng);
            switch (st) {
            case 'I': st = u < pf ? 'F' : u < 0.7 ? 'C' : 'I'; break;
            case 'C': st = u < pf ? 'F' : 'E'; break;
            case 'E': st = u < 0.6 ? 'I' : 'C'; break;
            case 'F': st = u < 0.4 ? 'F' : u < 0.8 ? 'O' : 'R'; break;
            case 'O': st = u < 0.7 ? 'R' : 'O'; break;
            default: st = 'I'; break;
            }
        }
        fputc(st, f);
        if (k % 100 == 99) fputc('\n', f);
    }
    fputc('\n', f);
    fclose(f);

    printf("%s: %d nodes, %d roads, %d sites, %d trips, %ld events -> %s\n", P->name, N, edges, P->sites, ntrips, P->events, out);
    free(x); free(y); free(z); free(dem); free(id); free(used);
    return 0;
}
