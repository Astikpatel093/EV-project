// scenario_io.hpp - the persistence layer: read and write scenario directories.
//
// A scenario directory holds (columns in brackets are optional):
//   scenario.cfg    key = value lines (see docs/data.md)
//   nodes.csv       id,[lat],[lon],[elev_m],[type],[name]
//   roads.csv       id,from,to,distance_km,[travel_time_min],[energy_kwh]
//   stations.csv    id,node,power_kw,ports,[name],[connector],[status],[install_cost_inr],[maint_period_h],[maint_offset_h]
//   candidates.csv  id,node,install_cost_inr,power_kw,ports,[name],[benefit],[suitability],[connector],[maint_period_h],[maint_offset_h]
//   vehicles.csv    id,battery_kwh,charge_kwh,consumption_kwh_per_km,reserve_kwh,[model],[connector],[max_charge_kw]
//   trips.csv       id,vehicle,from,to,[depart_min],[start_charge_kwh]
//   sessions.csv    id,station,start_min,end_min
//   events.txt      optional station event log
// scenario.cfg, nodes.csv and roads.csv are required; the others may be absent (= no records).
//
// Loading is all-or-nothing: the first problem throws ev::DataError("file:line: reason") and no
// partially loaded Scenario is ever returned, so an application's current scenario stays valid.
#pragma once

#include <optional>
#include <string>

#include "ev/models/scenario.hpp"

namespace ev {

// File contents already in memory (used by the loader, the tests and the web server).
struct ScenarioTexts {
    std::string label = "scenario";   // directory name used in error messages
    std::optional<std::string> config, nodes, roads, stations, candidates, vehicles, trips, sessions, events;
};

Scenario parse_scenario(const ScenarioTexts &texts);
Scenario load_scenario(const std::string &directory);
ScenarioTexts read_scenario_texts(const std::string &directory);   // missing optional files stay empty

// Writes every file of the scenario to `directory` (created if needed). `comment` lines are
// written at the top of each CSV (e.g. "SYNTHETIC data generated by ev33_gen --seed 33").
void write_scenario(const Scenario &s, const std::string &directory, const std::vector<std::string> &comment);

// Small file helpers (binary mode, so output is byte-identical on Windows and Linux).
std::optional<std::string> read_text_file(const std::string &path);
void write_text_file(const std::string &path, const std::string &text);   // throws std::runtime_error
void make_directories(const std::string &path);                           // like mkdir -p

// Config file in the same "key = value" form.
ScenarioConfig parse_config(const std::string &text, const std::string &file);
std::string format_config(const ScenarioConfig &c);

} // namespace ev
